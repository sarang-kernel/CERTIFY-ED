"""Regenerate docs/api.md from the docstrings of the public names: python docs/make_api.py"""
import inspect
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
import certify_ed as ce  # noqa: E402
from certify_ed import exact_sectors, checker  # noqa: E402
from certify_ed.apps import aklt  # noqa: E402
from certify_ed.apps.aklt import kernel  # noqa: E402
from certify_ed.apps.pyrochlore import spin_half, spin_one  # noqa: E402
from certify_ed.compat import symveig  # noqa: E402


def entry(name, obj):
    try:
        sig = str(inspect.signature(obj))
    except (TypeError, ValueError):
        sig = ""
    doc = (inspect.getdoc(obj) or "").split("\n\n")[0].replace("\n", " ")
    return f"* `{name}{sig if len(sig) < 140 else '(...)'}`  \n  {doc}"


GROUPS = {
    "Model specification": ["LocalSpace", "ModelSpec", "spec_from_quspin", "heisenberg_chain", "tfim_chain",
                            "heisenberg_square", "spinless_fermion_chain", "bose_hubbard_chain", "spin1_heisenberg_chain"],
    "Reference operators and sectors": ["build_bitwise", "build_kron", "cross_construct", "SpecOperator", "StateSet",
                                        "full_state_set", "u1_state_set", "magnetization_state_set", "translation",
                                        "spin_flip", "reflection", "cyclic_isometry", "sector_matrix"],
    "Certification": ["Claim", "Options", "certify", "Certificate", "OperatorAdapter", "enclose", "kato_temple",
                      "inertia_count", "probe_float_environment"],
    "Importers": ["claim_from_quspin", "claim_from_arrays", "claim_from_npz", "claim_from_hdf5", "export_npz"],
    "Whole-spectrum enclosure": ["enclose_spectrum", "SpectrumEnclosure", "SpectrumInterval"],
    "Exact layer": ["exact_matrix", "exact_eigenpair_radii", "exact_recheck_lowest", "exact_recheck_sector_lowest",
                    "site_permutation"],
}

lines = ["# API overview", "", "Generated by `docs/make_api.py` from the docstrings of the public names.", ""]
for g, names in GROUPS.items():
    lines += [f"## {g}", ""] + [entry(n, getattr(ce, n)) for n in names] + [""]
lines += ["## Exact layer (module level)", "", entry("exact_sectors.exact_count_below", exact_sectors.exact_count_below),
          entry("checker.inertia_exact", checker.inertia_exact), entry("checker.is_hermitian_exact", checker.is_hermitian_exact), ""]
lines += ["## Applications", "", entry("apps.aklt.certify_lattice", aklt.certify_lattice),
          entry("apps.aklt.eta_float", aklt.eta_float), entry("apps.aklt.square_octagon_criterion", aklt.square_octagon_criterion),
          entry("apps.aklt.kernel.kernel_check", kernel.kernel_check),
          entry("apps.pyrochlore.spin_half.certify_crown", spin_half.certify_crown),
          entry("apps.pyrochlore.spin_one.printed_coupling_check", spin_one.printed_coupling_check),
          entry("apps.pyrochlore.spin_one.landscape", spin_one.landscape), ""]
lines += ["## symveig compatibility", ""] + [entry(f"compat.symveig.{n}", getattr(symveig, n))
                                          for n in ("enclose_global", "enclose_sectors", "summary_stats")] + [""]
import certify_ed.cli as _cli  # noqa: E402
import certify_ed.provenance as _prov  # noqa: E402
lines += ["## Command line", "", "```", _cli.__doc__.strip(), "```", ""]
lines += ["## Provenance", "", entry("provenance.source_fingerprint", _prov.source_fingerprint),
          f"  Files outside the fingerprint: {', '.join(_prov.NON_COMPUTATIONAL)}", ""]
with open(os.path.join(os.path.dirname(os.path.abspath(__file__)), "api.md"), "w") as f:
    f.write("\n".join(lines))
