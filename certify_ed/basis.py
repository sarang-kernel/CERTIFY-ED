"""Reference symmetry sectors, built as explicit isometries.

CERTIFY-ED does not try to be a fast symmetric-basis ED code. It builds sector
bases in the simplest verifiable way: a sector is the range of an isometry V
(d x d_s, V^dagger V = I) obtained by applying the group projector to orbit
representatives. Sector Hamiltonians are then H_s = V^dagger H V. The same
objects are used to AUDIT a producer's sector decomposition (certify_ed.sectors).

Implemented groups:
  * U(1): fixed digit sum (magnetization for spins, particle number for
    fermions/bosons) -> a StateSet (no phases).
  * cyclic groups generated by a state map g with phase: translation by one
    site (with the fermionic reordering sign), global spin flip, reflection.
"""

from __future__ import annotations

import itertools
from dataclasses import dataclass
from typing import Callable, Tuple

import numpy as np
import scipy.sparse as sp

from .construct import StateSet, _popcount
from .spec import ModelSpec


# ---------------------------------------------------------------------------
# U(1)
# ---------------------------------------------------------------------------

def digit_sum(states: np.ndarray, q: int, N: int) -> np.ndarray:
    s = states.copy()
    tot = np.zeros(states.shape, dtype=np.int64)
    for _ in range(N):
        tot += s % q
        s //= q
    return tot


def u1_state_set(spec: ModelSpec, total: int, label: str = "") -> StateSet:
    """States whose digit sum equals `total` (e.g. N_up for spin-1/2)."""
    q, N = spec.q, spec.n_sites
    if q == 2 and 2 ** N > 2 ** 24:
        st = np.array(sorted(sum(1 << (N - 1 - i) for i in c)
                             for c in itertools.combinations(range(N), total)), dtype=np.int64)
    else:
        chunks = []
        dim = q ** N
        step = 1 << 22
        for a in range(0, dim, step):
            arr = np.arange(a, min(dim, a + step), dtype=np.int64)
            chunks.append(arr[digit_sum(arr, q, N) == total])
        st = np.concatenate(chunks) if chunks else np.zeros(0, dtype=np.int64)
    return StateSet(st, spec.state_order, label or f"digit_sum={total}")


def magnetization_state_set(spec: ModelSpec, two_Sz: int) -> StateSet:
    """Spin models: fixed total S^z (given as 2*S^z to stay integral)."""
    from fractions import Fraction
    S = Fraction(spec.local.spin)
    tot2 = two_Sz + int(2 * S) * spec.n_sites
    if tot2 % 2:
        raise ValueError("2*Sz has wrong parity for this N and S")
    return u1_state_set(spec, tot2 // 2, label=f"2Sz={two_Sz}")


# ---------------------------------------------------------------------------
# cyclic symmetry groups
# ---------------------------------------------------------------------------

@dataclass
class CyclicSymmetry:
    name: str
    order: int
    apply: Callable[[np.ndarray], Tuple[np.ndarray, np.ndarray]]  # states -> (states', phase)


def translation(spec: ModelSpec) -> CyclicSymmetry:
    """T: site i -> i+1 (mod N). Fermions acquire (-1)^{(n_f-1) n_{N-1}}."""
    q, N = spec.q, spec.n_sites
    top = q ** (N - 1)
    fermi = spec.local.is_fermionic

    def apply(s):
        last = s % q
        s2 = s // q + last * top
        if fermi:
            nf = _popcount(s)
            phase = np.where((last == 1) & ((nf - 1) % 2 == 1), -1.0, 1.0)
        else:
            phase = np.ones(s.shape)
        return s2, phase.astype(complex)
    return CyclicSymmetry("translation", N, apply)


def spin_flip(spec: ModelSpec) -> CyclicSymmetry:
    """Global flip m -> -m on every site (order 2). Spin models only."""
    if spec.local.kind != "spin":
        raise ValueError("spin flip only defined for spin models")
    top = spec.q ** spec.n_sites - 1
    return CyclicSymmetry("spin_flip", 2, lambda s: (top - s, np.ones(s.shape, dtype=complex)))


def reflection(spec: ModelSpec) -> CyclicSymmetry:
    """Site i -> N-1-i (order 2). Bosons/spins only (fermionic sign omitted)."""
    if spec.local.is_fermionic:
        raise NotImplementedError("fermionic reflection sign not implemented")
    q, N = spec.q, spec.n_sites

    def apply(s):
        out = np.zeros_like(s)
        t = s.copy()
        for _ in range(N):
            out = out * q + t % q
            t //= q
        return out, np.ones(s.shape, dtype=complex)
    return CyclicSymmetry("reflection", 2, apply)


def cyclic_isometry(states: StateSet, g: CyclicSymmetry, j: int,
                    drop_tol: float = 1e-10) -> sp.csr_matrix:
    """Isometry onto the character-j subspace of g inside span(states).

    Columns are normalised P_j |r> for orbit representatives r (smallest
    integer of each orbit), P_j = (1/n) sum_m exp(-2 pi i j m / n) g^m.
    Rows are indexed in the order of `states` (states.states_in_order()).
    The state set must be closed under g (e.g. a U(1) set under translation).
    """
    n = g.order
    s_all = states.states_asc
    # orbit representatives: minimum over the orbit
    orbit_min = s_all.copy()
    cur = s_all.copy()
    for _ in range(n - 1):
        cur, _ = g.apply(cur)
        orbit_min = np.minimum(orbit_min, cur)
    reps = np.unique(orbit_min)
    # accumulate sum_m chi^{-m} phase_m g^m |r>
    rows, cols, vals = [], [], []
    cur = reps.copy()
    ph = np.ones(reps.shape, dtype=complex)
    colidx = np.arange(reps.size)
    omega = np.exp(-2j * np.pi * j / n)
    for m in range(n):
        idx, found = states.index_of(cur)
        if not np.all(found):
            raise ValueError("state set is not closed under the symmetry")
        rows.append(idx)
        cols.append(colidx)
        vals.append(ph * omega ** m)
        cur, p = g.apply(cur)
        ph = ph * p
    V = sp.coo_matrix((np.concatenate(vals), (np.concatenate(rows), np.concatenate(cols))),
                      shape=(states.size, reps.size)).tocsc()
    V.sum_duplicates()
    norms = np.sqrt(np.asarray(abs(V).power(2).sum(axis=0)).ravel())
    keep = norms > drop_tol * n
    V = V[:, keep] @ sp.diags(1.0 / norms[keep])
    V = V.tocsr()
    V.eliminate_zeros()
    return V


def sector_matrix(H: sp.spmatrix, V: sp.spmatrix) -> sp.csr_matrix:
    """Sector block V^H H V of an isometry V."""
    Hs = (V.conj().T @ H @ V).tocsr()
    Hs.sum_duplicates()
    return Hs
