"""Write the three reference producer bundles under conformance/reference/ (run from the repository root).

All three describe the same model, the S=1/2 Heisenberg chain on 6 sites (dimension 64), so that a third-party
writer can diff its own bundle against a known-good one format by format:

  dense-arrays/    text files: eigenvalues.csv, eigenvectors.csv (columns), operator.txt (dense 64 x 64), spec.json
  npz/             eigenvalues.npz, eigenvectors.npz, operator.npz (scipy sparse CSR), spec.json
  matrix-free/     eigenvalues.csv, eigenvectors.csv, spec.json and no operator file: the statements concern the
                   reference matrix built from the declared model (S1 compares the two independent constructions)

Each bundle carries meta.json (schema certify-ed/producer-bundle/1.0) and expected.json with the statuses
`certify-ed conform` must reproduce. The eigenpairs come from scipy.linalg.eigh of the dense matrix; the
bundles are regenerated by this script and checked by the test suite (tests/test_schema_conformance.py).
"""
import json
import os
import shutil
import sys

import scipy.linalg as la

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

import certify_ed as ce  # noqa: E402
from certify_ed.io.bundle import META_SCHEMA, write_bundle  # noqa: E402

HERE = os.path.dirname(os.path.abspath(__file__))
REFERENCE = os.path.join(HERE, "reference")

PRODUCER = {"name": "certify-ed reference bundles", "version": "1.0",
            "note": "scipy.linalg.eigh of the dense matrix built by certify_ed.build_bitwise"}


def make(root=REFERENCE):
    spec = ce.heisenberg_chain(6)
    H = ce.build_bitwise(spec)
    w, V = la.eigh(H.toarray())
    os.makedirs(root, exist_ok=True)
    out = {}
    # 1. dense text arrays, dense operator
    d = os.path.join(root, "dense-arrays")
    shutil.rmtree(d, ignore_errors=True)
    write_bundle(d, w[:4], V[:, :4], H.toarray(), spec, fmt="csv", operator_fmt="txt", kind="lowest",
                 meta={"producer": PRODUCER, "description": "Heisenberg chain, 6 sites: lowest 4 eigenpairs, dense text"})
    out[d] = {"S1.model_fidelity": "CERTIFIED", "S2.eigenpairs": "CERTIFIED", "S3.completeness": "CERTIFIED"}
    # 2. npz arrays, sparse operator
    d = os.path.join(root, "npz")
    shutil.rmtree(d, ignore_errors=True)
    write_bundle(d, w[:4], V[:, :4], H, spec, fmt="npz", kind="lowest",
                 meta={"producer": PRODUCER, "description": "Heisenberg chain, 6 sites: lowest 4 eigenpairs, npz"})
    out[d] = {"S1.model_fidelity": "CERTIFIED", "S2.eigenpairs": "CERTIFIED", "S3.completeness": "CERTIFIED"}
    # 3. matrix-free: spec only, no operator file
    d = os.path.join(root, "matrix-free")
    shutil.rmtree(d, ignore_errors=True)
    write_bundle(d, w[:1], V[:, :1], None, spec, fmt="csv", kind="lowest",
                 meta={"producer": PRODUCER, "preset": "lab-minimal",
                       "description": "Heisenberg chain, 6 sites: ground state, operator applied from spec.json"})
    out[d] = {"S1.model_fidelity": "CERTIFIED", "S2.eigenpairs": "CERTIFIED", "S3.completeness": "NOT_CHECKED"}
    for d, expected in out.items():
        with open(os.path.join(d, "expected.json"), "w", encoding="utf-8", newline="\n") as f:
            json.dump(expected, f, indent=1)
            f.write("\n")
        # meta.json with LF line endings and sorted keys, so the committed files are stable
        mp = os.path.join(d, "meta.json")
        with open(mp, encoding="utf-8") as f:
            meta = json.load(f)
        assert meta["schema"] == META_SCHEMA
        with open(mp, "w", encoding="utf-8", newline="\n") as f:
            json.dump(meta, f, indent=1, sort_keys=True)
            f.write("\n")
    return list(out)


if __name__ == "__main__":
    for p in make():
        print(p)
