def macro(k, v, note=None, provide=False):
    M[k] = str(v)
    if note:
        NOTES[k] = " ".join(str(note).split())
    if provide:
        PROVIDE.add(k)


def pending(k, reason):
    """The manuscript uses \\k but this run has no record for it: numbers_todo.tex gets \\todo{reason}."""
    PENDING[k] = " ".join(str(reason).split())


def thin(n):
    """Integer with thin-space thousands separators (math-safe), as in make_numbers.py."""
    return f"{int(n):,}".replace(",", "\\,")


def read_log(prefix):
    """run.log of the latest record of an experiment ('' if missing): a few numbers live only in the log."""
    c = sorted(d for d in glob.glob(os.path.join(RES, prefix + "_2*")) if os.path.isdir(d))
    if not c:
        return ""
    try:
        with open(os.path.join(c[-1], "run.log"), encoding="utf-8", errors="replace") as f:
            return f.read()
    except OSError:
        return ""


def unreduced_block(log, lattice):
    """Largest bordered block of an E10 lattice before the symmetry reduction, from the run.log line
    'largest symmetry-adapted bordered blocks [...] (unreduced max N)' that follows the lattice's header
    (the data.json record stores only the reduced size, D-38 / MS-N11). None if not in the log."""
    import re
    m = re.search(r"^\[[^\]]*\]\s+" + re.escape(lattice) + r": floating-point eta.*$", log, re.M)
    if not m:
        return None
    m2 = re.search(r"\(unreduced max (\d+)\)", log[m.end():])
    nxt = re.search(r"^\[[^\]]*\]\s+\w+: floating-point eta", log[m.end():], re.M)
    if not m2 or (nxt and m2.start() > nxt.start()):
        return None
    return int(m2.group(1))


def symveig_outside_count(text):
    """'N of 64 true eigenvalues lie outside' from docs/symveig_audit.md (the project's audit of symveig
    1.0.0 under a staggered transverse field, RA-32); None if the sentence is missing."""
    import re
    m = re.search(r"(\d+) of (\d+) true eigenvalues lie outside", text or "")
    return (int(m.group(1)), int(m.group(2))) if m else None


def write_pending(path, items):
    """generated/numbers_todo.tex: the macros still waiting for a record, each as \\todo{reason}; an empty
    file (comment only) when every macro of the manuscript is emitted. main.tex inputs it unconditionally."""
    with open(path, "w", encoding="utf-8") as f:
        f.write("% generated by experiments/make_numbers_apps.py -- do not edit\n")
        if not items:
            f.write("% no pending macros: every number of the manuscript is emitted from the run records\n")
        for k, reason in sorted(items.items()):
            f.write(f"\\newcommand{{\\{k}}}{{\\todo{{{reason}}}}}\n")


