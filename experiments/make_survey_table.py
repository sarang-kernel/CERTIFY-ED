"""Generate the practice-survey macros and table for the manuscript from survey_coded.csv.

Usage: python make_survey_table.py <survey_dir> <generated_dir>

<survey_dir> holds survey_coded.csv, survey_handcheck.csv and survey_sample.json (PREREG_practice_survey.md
v0.2). Writes <generated_dir>/numbers_survey.tex and <generated_dir>/tables/survey_table.tex.

Every number is computed here from the CSV. Model-coded fractions are labelled PROVISIONAL in the output
because the pre-registered hand check left 9 of 13 fields below 80 % agreement (RESULT_practice_survey.md
section 5); the macros carry that flag so the manuscript cannot quote them as firm.
"""
import csv
import json
import math
import os
import sys
from collections import Counter

QUANTITIES = [  # (label in the CSV, macro suffix)
    ("ground energy", "GroundEnergy"), ("gaps", "Gaps"), ("excited levels", "ExcitedLevels"),
    ("degeneracies", "Degeneracies"), ("quantum numbers/labels", "QuantumNumbers"),
    ("correlation functions", "Correlations"), ("structure factor", "StructureFactor"),
    ("order parameter", "OrderParameter"), ("entanglement entropy/spectrum", "Entanglement"),
    ("fidelity/susceptibility", "Fidelity"), ("thermodynamics (full spectrum)", "Thermodynamics"),
    ("dynamical response/spectral function", "Dynamics"), ("time evolution", "TimeEvolution"),
    ("level statistics", "LevelStatistics"), ("finite-size extrapolation", "FiniteSize"), ("other", "Other"),
]
EVIDENCE = [
    ("residual or convergence tolerance stated", "Residual"), ("comparison with another code", "OtherCode"),
    ("comparison with literature value", "Literature"), ("comparison with analytic limit", "AnalyticLimit"),
    ("symmetry/sum-rule check", "SumRule"), ("none stated", "NoneStated"),
]
USES = [("lemma in a rigorous argument", "Lemma"), ("benchmark anchor for another method", "Anchor")]


def wilson(k, n, z=1.959963984540054):
    if n == 0:
        return (0.0, 0.0)
    p = k / n
    d = 1 + z * z / n
    c = (p + z * z / (2 * n)) / d
    h = z * math.sqrt(p * (1 - p) / n + z * z / (4 * n * n)) / d
    return (max(0.0, c - h), min(1.0, c + h))


def multi(rows, col):
    c = Counter()
    for r in rows:
        for x in (r.get(col) or "").split(";"):
            x = x.strip()
            if x:
                c[x] += 1
    return c


def pct(k, n):
    lo, hi = wilson(k, n)
    return f"{100 * k / n:.0f}\\,\\% [{100 * lo:.0f}, {100 * hi:.0f}]"


def main(survey_dir, gen_dir):
    rows = list(csv.DictReader(open(os.path.join(survey_dir, "survey_coded.csv"), encoding="utf-8")))
    analysis = [r for r in rows if r.get("in_analysis_set") == "1"]
    n = len(analysis)
    n_sub = len(rows)
    sample = json.load(open(os.path.join(survey_dir, "survey_sample.json"), encoding="utf-8"))
    n_full = len(sample["records"]) if isinstance(sample, dict) and "records" in sample else len(sample)
    n_replaced = sum(1 for r in rows if (r.get("text_source") or "").startswith("replacement"))
    hand = list(csv.DictReader(open(os.path.join(survey_dir, "survey_handcheck.csv"), encoding="utf-8")))
    agree_cols = [c for c in hand[0].keys() if c.startswith("agree_") or c.startswith("jaccard_")]
    agreement = {}
    for c in agree_cols:
        vals = [float(h[c]) for h in hand if h.get(c) not in (None, "")]
        agreement[c] = sum(vals) / len(vals) if vals else float("nan")
    min_agree = min(v for v in agreement.values() if not math.isnan(v))
    n_fields_below = sum(1 for v in agreement.values() if v < 0.8)
    exclusions = Counter(r.get("exclusion_reason") or "" for r in rows if r.get("in_analysis_set") != "1")

    q = multi(analysis, "quantities")
    e = multi(analysis, "evidence")
    u = multi(analysis, "use")
    prec = sum(1 for r in analysis if (r.get("precision_stated") or "").strip() == "yes")

    lines = ["% generated/numbers_survey.tex -- generated by experiments/make_survey_table.py; do not edit",
             "% Source: survey_coded.csv (PREREG_practice_survey.md v0.2). Model-coded fractions are PROVISIONAL:",
             f"% the hand check left {n_fields_below} of {len(agreement)} fields below 80 % agreement (minimum {100 * min_agree:.0f} %).",
             "\\newcommand{\\SurveyProvisional}{(model-coded, provisional)}",
             f"\\newcommand{{\\SurveyN}}{{{n}}}",
             f"\\newcommand{{\\SurveyNsub}}{{{n_sub}}}",
             f"\\newcommand{{\\SurveyNfull}}{{{n_full}}}",
             f"\\newcommand{{\\SurveyNreplaced}}{{{n_replaced}}}",
             f"\\newcommand{{\\SurveyNexcluded}}{{{n_sub - n}}}",
             f"\\newcommand{{\\SurveyHandcheckN}}{{{len(hand)}}}",
             f"\\newcommand{{\\SurveyHandcheckAgreement}}{{{100 * min_agree:.0f}\\,\\%}}",
             f"\\newcommand{{\\SurveyHandcheckFieldsBelow}}{{{n_fields_below}}}",
             f"\\newcommand{{\\SurveyHandcheckFields}}{{{len(agreement)}}}",
             "\\newcommand{\\SurveyDateRange}{2024-01-01 to 2026-10-21}"]
    for label, suf in QUANTITIES:
        lines.append(f"\\newcommand{{\\SurveyFrac{suf}}}{{{pct(q.get(label, 0), n)}}}")
    for label, suf in EVIDENCE:
        lines.append(f"\\newcommand{{\\SurveyEvidence{suf}}}{{{pct(e.get(label, 0), n)}}}")
    for label, suf in USES:
        lines.append(f"\\newcommand{{\\SurveyUse{suf}}}{{{pct(u.get(label, 0), n)}}}")
    lines.append(f"\\newcommand{{\\SurveyPrecisionStated}}{{{pct(prec, n)}}}")
    for c, v in sorted(agreement.items()):
        name = c.replace("agree_", "").replace("jaccard_", "").replace("_", "")
        lines.append(f"\\newcommand{{\\SurveyAgree{name}}}{{{100 * v:.0f}\\,\\%}}")
    os.makedirs(os.path.join(gen_dir, "tables"), exist_ok=True)
    with open(os.path.join(gen_dir, "numbers_survey.tex"), "w", encoding="utf-8") as f:
        f.write("\n".join(lines) + "\n")

    t = ["% generated/tables/survey_table.tex -- generated by experiments/make_survey_table.py; do not edit",
         "\\begin{tabular}{@{}l r r l@{}}", "\\toprule",
         "Item & $k$ & \\% & Wilson 95\\,\\% CI \\\\", "\\midrule",
         f"\\multicolumn{{4}}{{@{{}}l}}{{\\textit{{Quantities reported from ED}} ($n={n}$; model-coded, provisional)}} \\\\"]
    for label, _ in sorted(QUANTITIES, key=lambda x: -q.get(x[0], 0)):
        k = q.get(label, 0); lo, hi = wilson(k, n)
        lab = label.replace("/", "/\\allowbreak ")
        t.append(f"\\quad {lab} & {k} & {100 * k / n:.0f} & [{100 * lo:.0f}, {100 * hi:.0f}] \\\\")
    t.append("\\midrule")
    t.append(f"\\multicolumn{{4}}{{@{{}}l}}{{\\textit{{Evidence of correctness given}} ($n={n}$; model-coded, provisional)}} \\\\")
    for label, _ in sorted(EVIDENCE, key=lambda x: -e.get(x[0], 0)):
        k = e.get(label, 0); lo, hi = wilson(k, n)
        t.append(f"\\quad {label} & {k} & {100 * k / n:.0f} & [{100 * lo:.0f}, {100 * hi:.0f}] \\\\")
    t.append("\\midrule")
    t.append(f"\\multicolumn{{4}}{{@{{}}l}}{{\\textit{{Use of the ED numbers}} ($n={n}$)}} \\\\")
    for label, _ in USES:
        k = u.get(label, 0); lo, hi = wilson(k, n)
        t.append(f"\\quad {label} & {k} & {100 * k / n:.0f} & [{100 * lo:.0f}, {100 * hi:.0f}] \\\\")
    t += ["\\bottomrule", "\\end{tabular}"]
    with open(os.path.join(gen_dir, "tables", "survey_table.tex"), "w", encoding="utf-8") as f:
        f.write("\n".join(t) + "\n")
    print(f"survey: n={n} of {n_sub} coded ({n_full} in the population); exclusions {dict(exclusions)}; "
          f"hand check min agreement {100 * min_agree:.0f} % ({n_fields_below}/{len(agreement)} fields < 80 %)")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1], sys.argv[2]))
