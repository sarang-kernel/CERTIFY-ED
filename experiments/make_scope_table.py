"""Generate the manuscript's scope-matrix table from docs/SCOPE_MATRIX.md.

Usage: python make_scope_table.py <repo_root> <generated_dir> [survey_for_scope.json]

Reads the Markdown table of docs/SCOPE_MATRIX.md (columns: quantity | states today | narrowable | out of scope
and why | mathematics needed) and writes <generated_dir>/tables/scope_matrix.tex with a compact view:
the quantity, the statement ids found in the 'states today' cell, a default-scope word, the reason codes found
in the out-of-scope cell, and (optionally) the fraction of surveyed papers reporting the quantity.
The long prose cells stay in docs/SCOPE_MATRIX.md, which the manuscript cites.
"""
import json
import os
import re
import sys

STMT = re.compile(r"\b(S[1-8])\b")
CODE = re.compile(r"\b([A-Z][A-Z_]{5,})\b")
SURVEY_KEY = {  # scope-matrix row label (lower-cased start) -> survey quantity label
    "ground-state energy": "ground energy", "ground energy": "ground energy", "gaps": "gaps",
    "excited states": "excited levels", "degeneracies": "degeneracies",
    "quantum numbers": "quantum numbers/labels", "correlation functions": "correlation functions",
    "structure factors": "structure factor", "structure factor": "structure factor",
    "order parameters": "order parameter", "order parameter": "order parameter",
    "entanglement": "entanglement entropy/spectrum", "thermodynamics": "thermodynamics (full spectrum)",
    "dynamical response": "dynamical response/spectral function", "time evolution": "time evolution",
    "level statistics": "level statistics", "finite-size extrapolation": "finite-size extrapolation",
}


def tex_escape(s):
    s = (s.replace("\u27e8", "$\\langle ").replace("\u27e9", "\\rangle$").replace("\u2212", "-")
         .replace("\u2192", "to").replace("\u00b7", " "))
    s = "".join(ch for ch in s if ord(ch) < 128)
    return (s.replace("&", "\\&").replace("%", "\\%").replace("#", "\\#").replace("|", "").replace("**", "")
            .replace("\"", "''"))


def escape_underscores(line):
    """Escape _ outside $...$ math spans only."""
    parts = line.split("$")
    return "$".join(pt if i % 2 else pt.replace("_", "\\_") for i, pt in enumerate(parts))


def parse_rows(md):
    rows = []
    for line in md.splitlines():
        if not line.startswith("|") or set(line.strip()) <= set("|-: "):
            continue
        protected = line.replace("\\|", "\x00")  # escaped pipes inside a cell (e.g. a norm) are not separators
        cells = [c.strip().replace("\x00", "|") for c in protected.strip().strip("|").split("|")]
        if len(cells) < 4 or cells[0].lower().startswith("quantity labs"):
            continue
        rows.append(cells)
    return rows


def main(root, gen_dir, survey_json=None):
    md = open(os.path.join(root, "docs", "SCOPE_MATRIX.md"), encoding="utf-8").read()
    rows = parse_rows(md)
    survey = None
    if survey_json and os.path.exists(survey_json):
        survey = json.load(open(survey_json, encoding="utf-8"))
    out = ["% generated/tables/scope_matrix.tex -- generated by experiments/make_scope_table.py from docs/SCOPE_MATRIX.md; do not edit",
           "\\begin{tabular}{@{}p{0.23\\textwidth} p{0.14\\textwidth} p{0.12\\textwidth} p{0.3\\textwidth} r@{}}",
           "\\toprule",
           "Reported quantity & Statement(s) & Default & Out of scope (reason code) & Survey \\% \\\\",
           "\\midrule"]
    n_rows = 0
    prev_codes, prev_caveat = [], False
    for cells in rows:
        quantity = re.sub(r"\*+", "", cells[0]).strip()
        states, out_scope = cells[1], cells[3]
        nothing = states.lower().startswith("nothing")
        stmts = [] if nothing else sorted(set(STMT.findall(states)), key=lambda s: int(s[1]))
        skip = {"UNVERIFIED", "INCONCLUSIVE", "CERTIFIED", "FAILED", "NOT", "HDF"}
        codes = sorted((set(CODE.findall(states)) | set(CODE.findall(out_scope))) - skip)
        cell = out_scope.strip().lower()
        # 'as above' inherits the previous row's restriction; any other non-empty cell is a documented
        # caveat even when it names no reason code (the prose of docs/SCOPE_MATRIX.md carries it)
        inherits = cell.startswith("as above")
        if inherits:
            codes = sorted(set(codes) | set(prev_codes))
        caveat = (bool(cell) and cell not in ("--", "-", "nothing", "none")) or (inherits and prev_caveat)
        if nothing:
            default = "out of scope"
        elif codes or caveat:
            default = "partly"
        else:
            default = "in scope"
        reason = ", ".join(codes)
        if caveat:
            reason = (reason + "; " if reason else "") + "see matrix"
        prev_codes, prev_caveat = codes, caveat

        frac = "--"
        if survey:
            key = next((v for k, v in SURVEY_KEY.items() if quantity.lower().startswith(k)), None)
            if key and key in survey.get("quantities", {}):
                frac = f"{100 * survey['quantities'][key]['fraction']:.0f}"
        out.append(f"{tex_escape(quantity)} & {', '.join(stmts) or '--'} & {default} & "
                   f"{tex_escape(reason) or '--'} & {frac} \\\\")
        n_rows += 1
    out = [escape_underscores(o) if "&" in o and "tabular" not in o else o for o in out]
    out += ["\\bottomrule", "\\end{tabular}"]
    os.makedirs(os.path.join(gen_dir, "tables"), exist_ok=True)
    with open(os.path.join(gen_dir, "tables", "scope_matrix.tex"), "w", encoding="utf-8") as f:
        f.write("\n".join(out) + "\n")
    print(f"scope matrix: {n_rows} rows written")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1], sys.argv[2], sys.argv[3] if len(sys.argv) > 3 else None))
