"""Exact (floating-point-free) re-check of 'lowest eigenvalues in a symmetry sector' claims.

The declared model is taken as an exact rational matrix (checker.exact_matrix: the scaled form K = D^-1 H D
with integer weights W = D^2, which covers every local space). Symmetry sectors of an
abelian group generated by commuting cyclic symmetries (translations, reflections, spin flip, any site
permutation) are spanned by unnormalised orbit sums w = sum_g conj(chi(g)) phase_g(s) e_{g s}. When every
character value is in {+1, -1, +i, -i} the w are Gaussian-integer vectors, mutually orthogonal, with
squared norms >= 1. The compressed matrices W^H (b den H - a den I) W = b W^H H_int W - a den W^H W are
Gaussian-integer Hermitian matrices; their real embeddings [[Re, -Im], [Im, Re]] (every eigenvalue
twice) are factored in floating point and the factorization residual is checked exactly
(checker.inertia_exact). Writing the congruence as Q N with Q orthonormal and N >= I diagonal, Sylvester's law and
Weyl's inequality give, with delta = beta / (b den):
    #(eig(H|sector) < g - delta) <= nu / 2 <= #(eig(H|sector) < g + delta).
Claimed vectors are projected onto the claimed sector exactly (integer arithmetic) before their residual
radius is computed, so Krylov-Bogolyubov applies to H restricted to the sector.
"""
from fractions import Fraction
from math import lcm
from typing import Dict, Sequence

import numpy as np

from .basis import CyclicSymmetry
from .checker import exact_matrix, inertia_exact


def site_permutation(spec, perm, name="site_permutation") -> CyclicSymmetry:
    """Symmetry s -> state with digit of site i moved to site perm[i] (spins and bosons)."""
    if spec.local.is_fermionic:
        raise NotImplementedError("fermionic site permutations need reordering signs")
    q, N = spec.q, spec.n_sites
    perm = list(perm)
    seen, order = set(), 1
    for i in range(N):
        if i in seen:
            continue
        L, j = 0, i
        while j not in seen:
            seen.add(j); j = perm[j]; L += 1
        order = lcm(order, L)

    def apply(s):
        out = np.zeros_like(s)
        for i in range(N):
            digit = (s // q ** (N - 1 - i)) % q
            out = out + digit * q ** (N - 1 - perm[i])
        return out, np.ones(s.shape, dtype=complex)
    return CyclicSymmetry(name, order, apply)


def _gauss_power_unused(n, k):
    """exp(-2 pi i k / n) as (re, im) integers; ValueError if not in {+-1, +-i}."""
    if (4 * k) % n:
        raise ValueError(f"character exp(-2 pi i {k}/{n}) is not a Gaussian integer")
    return [(1, 0), (0, -1), (-1, 0), (0, 1)][(4 * k // n) % 4]


class FiniteGroup:
    """Group generated by state maps (with +-1 phases), enumerated by closure on the state set.
    Elements are stored as (index map, integer phases) together with one word (exponents of the
    generators along a path) used to evaluate 1D characters; a character given by generator values is
    checked to be a homomorphism (every element gets the same value from every word reaching it)."""

    def __init__(self, gens: Sequence[CyclicSymmetry], states):
        self.gens = list(gens)
        self.states = states
        s0 = states.states_in_order()
        n = s0.size
        self.gen_maps = []
        for g in self.gens:
            s1, ph = g.apply(s0)
            idx, found = states.index_of(s1)
            if not np.all(found):
                raise ValueError(f"state set not closed under {g.name}")
            if not (np.all(np.isin(np.round(ph.real), (-1, 1))) and np.all(ph.imag == 0)):
                raise ValueError("only +-1 phases supported")
            self.gen_maps.append((idx.astype(np.int64), np.round(ph.real).astype(np.int64)))
        ident = (np.arange(n, dtype=np.int64), np.ones(n, dtype=np.int64))
        key = lambda e: (e[0].tobytes(), e[1].tobytes())
        self.elements_ = [(ident, ())]
        self._index = {key(ident): 0}
        self._edges = []                        # (from element, generator, to element)
        frontier = [0]
        while frontier:
            nxt = []
            for a in frontier:
                (ia, pa), wa = self.elements_[a]
                for gi, (ig, pg) in enumerate(self.gen_maps):
                    # apply element a, then generator: state t = ia[s] -> ig[t]; phase pa[s] * pg[ia[s]]
                    e = (ig[ia], pa * pg[ia])
                    k = key(e)
                    if k not in self._index:
                        self._index[k] = len(self.elements_)
                        self.elements_.append((e, wa + (gi,)))
                        nxt.append(self._index[k])
                    self._edges.append((a, gi, self._index[k]))
            frontier = nxt
            if len(self.elements_) > 100000:
                raise ValueError("group too large")

    @property
    def order(self):
        return len(self.elements_)

    def character(self, gen_values):
        """Values of the 1D character with the given generator values (Gaussian units (re, im)) on every
        element, or None if these generator values do not define a homomorphism."""
        vals = [None] * self.order
        vals[0] = (1, 0)
        for a, gi, b in self._edges:          # BFS order: vals[a] is set before edges from a are used
            if vals[a] is None:
                continue
            x, y = vals[a]; u, v = gen_values[gi]
            c = (x * u - y * v, x * v + y * u)
            if vals[b] is None:
                vals[b] = c
            elif vals[b] != c:
                return None
        # second pass to check all edges (some edges were visited before their source was set)
        for a, gi, b in self._edges:
            x, y = vals[a]; u, v = gen_values[gi]
            if vals[b] != (x * u - y * v, x * v + y * u):
                return None
        return vals


def orbit_columns(group: "FiniteGroup", chi):
    """Orbit sums w_s = sum_g conj(chi(g)) phase_g(s) e_{g s} for a 1D character chi (list of Gaussian
    units per element). Returns a list of dicts index -> (re, im), zero vectors dropped."""
    n = group.states.size
    rep = np.arange(n)
    for (idx, _), _ in group.elements_:
        rep = np.minimum(rep, idx)
    reps = np.unique(rep)
    cols = [dict() for _ in reps]
    pos = {int(r): k for k, r in enumerate(reps)}
    rlist = reps.tolist()
    for ((idx, ph), _), (cr, ci) in zip(group.elements_, chi):
        cr, ci = cr, -ci                         # conj(chi)
        tgt = idx[reps]; p = ph[reps]
        for k, (t, pp) in enumerate(zip(tgt.tolist(), p.tolist())):
            a, b = cols[k].get(t, (0, 0))
            cols[k][t] = (a + pp * cr, b + pp * ci)
    out = []
    for col in cols:
        col = {t: v for t, v in col.items() if v != (0, 0)}
        if col:
            out.append(col)
    return out


def sector_integer_matrix(ex, cols):
    """(Re, Im, D): V^H (W K den) V as Gaussian-integer arrays (object), V the orbit-sum columns, and
    D = diag(V^H W V). W K den = den D H D (exact_matrix), so this is the congruence of den H by D V."""
    R, C, RE, IM, den = ex.rows, ex.cols, ex.re, ex.im, ex.den
    wts = ex.weights
    n_cols = len(cols)
    owner = {}
    for o, col in enumerate(cols):
        for t, v in col.items():
            owner[t] = (o, v)
    rows_of = {}
    for r, c, a, b in zip(R.tolist(), C.tolist(), RE.tolist(), IM.tolist()):
        rows_of.setdefault(c, []).append((r, a, b))
    Are = np.zeros((n_cols, n_cols), dtype=object); Are[:] = 0
    Aim = np.zeros((n_cols, n_cols), dtype=object); Aim[:] = 0
    D = np.zeros(n_cols, dtype=object)
    for o, col in enumerate(cols):
        D[o] = sum(wts[t] * (a * a + b * b) for t, (a, b) in col.items())
        hv = {}
        for c, (wr, wi) in col.items():
            for r, a, b in rows_of.get(c, ()):
                x, y = hv.get(r, (0, 0))
                hv[r] = (x + a * wr - b * wi, y + a * wi + b * wr)
        for r, (x, y) in hv.items():
            if r not in owner:
                if (x, y) != (0, 0):
                    raise ValueError("H maps the sector outside the sector")
                continue
            o2, (vr, vi) = owner[r]
            wr_ = wts[r]
            # conj(v) * w_r * (x + i y)
            Are[o2, o] += wr_ * (vr * x + vi * y)
            Aim[o2, o] += wr_ * (vr * y - vi * x)
    return Are, Aim, D


def _count_sector_below(Are, Aim, D, g: Fraction, den: int):
    import flint
    m = Are.shape[0]
    a, b = g.numerator, g.denominator
    Mre = Are * b
    for i in range(m):
        Mre[i, i] = Mre[i, i] - a * den * D[i]
    Mim = Aim * b
    if any(int(x) != 0 for x in Mim.ravel()):
        big = np.block([[Mre, -Mim], [Mim, Mre]])
        factor = 2
    else:
        big = Mre
        factor = 1
    nu, _, beta = inertia_exact(big)
    if nu is None or nu % factor:
        return None, None
    return nu // factor, beta / (b * den)


def check_commutes(ex, group: "FiniteGroup"):
    """Exact check that every generator g (state map with phases) commutes with H:
    K[g r, g c] phase(r) phase(c) == K[r, c] for every stored entry of the scaled matrix, the entry sets
    agree, and the weights are invariant (w[g s] == w[s]), so that g also commutes with D and with H."""
    ent = {(int(r), int(c)): (a, b) for r, c, a, b in zip(ex.rows.tolist(), ex.cols.tolist(),
                                                           ex.re.tolist(), ex.im.tolist())}
    for gi, (idx, ph) in enumerate(group.gen_maps):
        if not all(ex.weights[int(t)] == ex.weights[s_] for s_, t in enumerate(idx)):
            return False, group.gens[gi].name + " (does not preserve the scaling weights)"
        img = {}
        for (r, c), (a, b) in ent.items():
            p_ = int(ph[r]) * int(ph[c])
            img[(int(idx[r]), int(idx[c]))] = (a * p_, b * p_)
        if img != ent:
            return False, group.gens[gi].name
    return True, None


def sector_matrices(ex, group, gens, fixed, log=None):
    """Integer congruence blocks for every 1D irrep with the fixed quantum numbers (others summed over).
    Returns (list of (quantum numbers, dim, (Re, Im, D))), dimension covered)."""
    import itertools
    fixed_ids = sorted(fixed)
    free = [i for i in range(len(gens)) if i not in fixed]
    mats, dim_sum = [], 0
    for js_free in itertools.product(*[range(gens[i].order) for i in free]):
        vals = [None] * len(gens)
        for i in fixed_ids:
            vals[i] = _unit(gens[i].order, fixed[i])
        for i, j in zip(free, js_free):
            vals[i] = _unit(gens[i].order, j)
        if any(v is None for v in vals):
            continue
        chi = group.character(vals)
        if chi is None:
            continue
        cols = orbit_columns(group, chi)
        if not cols:
            continue
        dim_sum += len(cols)
        qn = {gens[i].name: (fixed[i] if i in fixed else dict(zip(free, js_free))[i]) for i in range(len(gens))}
        mats.append((qn, len(cols), sector_integer_matrix(ex, cols)))
        if log:
            log(f"    sector {qn}: dim {len(cols)}")
    return mats, dim_sum


def exact_count_below(spec, states, gens, fixed, points, log=None):
    """Exact counts of eigenvalues of H below each point g (Fractions), restricted to the subspace with
    the fixed quantum numbers and summed over all other 1D irreps (decomposition completeness checked).
    Returns a list of {point, count, delta}: #(eig < g - delta) <= count <= #(eig < g + delta).
    A count of 0 proves lambda_min >= g - delta. No floating-point assumption."""
    ex = exact_matrix(spec, states)
    group = FiniteGroup(gens, states)
    okc, bad = check_commutes(ex, group)
    if not okc:
        raise ValueError(f"{bad} is not a symmetry of the declared model")
    fixed_ids = sorted(fixed)
    sub = FiniteGroup([gens[i] for i in fixed_ids], states)
    chi_sub = sub.character([_unit(gens[i].order, fixed[i]) for i in fixed_ids])
    dim_fixed = len(orbit_columns(sub, chi_sub))
    mats, dim_sum = sector_matrices(ex, group, gens, fixed, log)
    if dim_sum != dim_fixed:
        raise ValueError(f"1D Gaussian irreps cover {dim_sum} of {dim_fixed} dimensions")
    out = []
    for g in points:
        g = Fraction(g)
        tot, dmax = 0, Fraction(0)
        for qn, m, (Are, Aim, D) in mats:
            nu, delta = _count_sector_below(Are, Aim, D, g, ex.den)
            if nu is None:
                tot = None; break
            tot += nu; dmax = max(dmax, delta)
            if log:
                log(f"    sector {qn} (dim {m}): {nu} below {float(g):.12g}, delta {float(delta):.2e}")
        out.append({"point": g, "count": tot, "delta": dmax})
    return out, {"sectors": [{"quantum_numbers": qn, "dim": m} for qn, m, _ in mats], "dim": dim_fixed,
                 "group_order": group.order, "den": int(ex.den)}


def _unit(n, j):
    """exp(2 pi i j / n) as a Gaussian unit, or None."""
    if (4 * j) % n:
        return None
    return [(1, 0), (0, 1), (-1, 0), (0, -1)][(4 * j // n) % 4]


def exact_recheck_sector_lowest(spec, states, gens, fixed: Dict[int, int], lam, X, next_hint=None,
                                log=None):
    """Exact re-check of 'lam are the len(lam) lowest eigenvalues of H in the subspace where generator i
    has the 1D quantum number fixed[i] (character value exp(2 pi i j / order))'. All other generators
    are summed over their 1D characters; the decomposition is checked to be complete (sector dimensions
    add up to the dimension of the fixed subspace), so non-abelian groups are allowed as long as every
    irrep met is one-dimensional with Gaussian character values (e.g. translations at k = 0 or pi with
    reflection and spin flip). X: claimed vectors in the coordinates of `states`."""
    import itertools
    from .checker import _float_vector_to_int, scaled_test_vector, radius_exact, _components, _separation_points, _status
    ex = exact_matrix(spec, states)
    den = ex.den
    group = FiniteGroup(gens, states)
    okc, bad = check_commutes(ex, group)
    if not okc:
        return {"status": "FAILED", "reason": f"{bad} is not a symmetry of the declared model"}
    lam = np.atleast_1d(np.asarray(lam, dtype=float))
    X = np.asarray(X)
    if X.ndim == 1:
        X = X[:, None]
    # subgroup of the fixed generators and its character: exact projection of the claimed vectors
    fixed_ids = sorted(fixed)
    sub = FiniteGroup([gens[i] for i in fixed_ids], states)
    sub_vals = [_unit(gens[i].order, fixed[i]) for i in fixed_ids]
    if any(v is None for v in sub_vals):
        raise ValueError("fixed quantum numbers must have Gaussian character values")
    chi_sub = sub.character(sub_vals)
    if chi_sub is None:
        raise ValueError("fixed quantum numbers do not define a 1D character of their subgroup")
    dim_fixed = len(orbit_columns(sub, chi_sub))
    radii = []
    for i in range(X.shape[1]):
        xr, xi, _ = _float_vector_to_int(scaled_test_vector(ex, X[:, i]))
        pr = np.zeros(xr.size, dtype=object); pi_ = np.zeros(xr.size, dtype=object)
        for ((idx, ph), _), (cr, ci) in zip(sub.elements_, chi_sub):
            cr, ci = cr, -ci
            pho = ph.astype(object)
            np.add.at(pr, idx, (xr * cr - xi * ci) * pho)
            np.add.at(pi_, idx, (xr * ci + xi * cr) * pho)
        radii.append(radius_exact(ex, pr, pi_, lam[i]))
    comps = _components(lam, radii)
    pts = _separation_points(comps, next_hint)
    mats, dim_sum = sector_matrices(ex, group, gens, fixed, log)
    if dim_sum != dim_fixed:
        return {"status": "NOT_CHECKED", "reason": f"1D Gaussian irreps cover {dim_sum} of {dim_fixed} dimensions"}
    counts, ok, cum = [], True, 0
    for j, g in enumerate(pts):
        cum += comps[j][2]
        tot, dmax, fail = 0, Fraction(0), False
        for qn, m, (Are, Aim, D) in mats:
            nu, delta = _count_sector_below(Are, Aim, D, g, den)
            if nu is None:
                fail = True; break
            tot += nu; dmax = max(dmax, delta)
        if fail:
            counts.append({"point": float(g), "count": None}); ok = False; continue
        sep = comps[j][1] < g - dmax and (j + 1 >= len(comps) or comps[j + 1][0] > g + dmax)
        counts.append({"point": float(g), "count": tot, "claimed_below": cum, "delta": float(dmax),
                       "separated": bool(sep)})
        ok &= (tot == cum) and sep
    return {"status": _status(counts, ok), "radii": [float(r) for r in radii],
            "components": [[float(a), float(b), m] for a, b, m in comps], "counts": counts,
            "sectors": [{"quantum_numbers": qn, "dim": m} for qn, m, _ in mats], "dim_fixed": dim_fixed,
            "group_order": group.order, "den": int(den), "no_floating_point_assumption": True}
